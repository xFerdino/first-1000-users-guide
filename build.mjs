// Builds README.md (the guide) and index.html (the searchable directory) from channels.json,
// intro.md. No dependencies. Run: node build.mjs
// Exits 1 on bad data: a missing field, an unknown chapter/cost/status/source, a duplicate
// URL, a dead link, or an entry with no check date. Re-run check-links.mjs first to refresh.

import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("./", import.meta.url);
const read = (f) => readFileSync(new URL(f, dir), "utf8");

export const CHAPTERS = [
  ["launch", "Launch platforms", "Daily and weekly launch boards. Most now run a free queue that takes weeks, plus a paid lane; many free listings need a backlink."],
  ["communities", "Communities and forums", "Places where developers and makers talk. Here you earn attention by writing something useful, not by posting a link."],
  ["reddit", "Reddit", "Each subreddit sets its own self-promotion rules, and many now push developers into one weekly thread or a sister sub. Reddit blocks automated readers, so these rules come from mirror sites or memory. Open the sidebar before you post."],
  ["social", "Social and build-in-public", "Your own audience, built post by post. Slow to start, and the only channel you own."],
  ["directories", "Directories and \"alternative to\" sites", "Slow, but they bring search traffic for years. \"Alternative to\" sites catch people at the moment they leave a competitor."],
  ["ai", "AI tool directories", "Only worth it when AI is the product. Trimmed hard: the original list had over a hundred, most with no real traffic."],
  ["mobile", "Mobile app channels", "The store page is the biggest channel for an app. Around it sit featuring nominations, tester communities and alternative stores."],
  ["newsletters", "Newsletters, podcasts and press", "Editors pick stories, not products. Pitch a story, short, with a link they can try."],
  ["chat", "Chat communities", "Discord, Slack and Telegram groups. Small, warm and slow; good for first testers."],
  ["europe", "Europe by language", "Local-language press and forums. A small market where a newcomer can still get noticed, for products that speak the language."],
];
const CHAPTER_KEYS = new Set(CHAPTERS.map((c) => c[0]));
const COSTS = new Set(["free", "paid", "freemium"]);
const STATUSES = new Set(["ok", "blocked"]);
const SOURCES = { site: "●", mirror: "◐", memory: "○" };
const REQUIRED = ["name", "url", "chapter", "tags", "what", "rules", "cost", "checked", "status", "source"];

export function validate(channels) {
  const errors = [];
  const seen = new Map();
  channels.forEach((c, i) => {
    const at = `#${i} ${c.name ?? "(no name)"}`;
    for (const f of REQUIRED) if (c[f] === undefined || c[f] === "" || (Array.isArray(c[f]) && !c[f].length)) errors.push(`${at}: missing ${f}`);
    if (c.chapter && !CHAPTER_KEYS.has(c.chapter)) errors.push(`${at}: unknown chapter ${c.chapter}`);
    if (c.cost && !COSTS.has(c.cost)) errors.push(`${at}: unknown cost ${c.cost}`);
    if (c.status && !STATUSES.has(c.status)) errors.push(`${at}: status ${c.status} (dead links must be fixed or removed)`);
    if (c.source && !SOURCES[c.source]) errors.push(`${at}: unknown source ${c.source}`);
    if (c.checked && !/^\d{4}-\d{2}-\d{2}$/.test(c.checked)) errors.push(`${at}: bad check date ${c.checked}`);
    for (const u of [c.url, c.submitUrl].filter(Boolean)) {
      if (!/^https:\/\//.test(u)) errors.push(`${at}: not https: ${u}`);
    }
    if (c.url) {
      const key = c.url.replace(/\/$/, "").toLowerCase();
      if (seen.has(key)) errors.push(`${at}: duplicate url (also ${seen.get(key)})`);
      seen.set(key, c.name);
    }
  });
  return errors;
}

const md = (s) => s.replace(/([\[\]|])/g, "\\$1");

function entryMd(c) {
  const submit = c.submitUrl && c.submitUrl !== c.url ? ` · [submit](${c.submitUrl})` : "";
  const warn = c.status === "blocked" ? " ⚠" : "";
  return `- **[${md(c.name)}](${c.url})**${warn} · ${c.cost}${submit}  \n  ${c.what}  \n  ${SOURCES[c.source]} *${c.rules}*`;
}

function buildReadme(channels, checked) {
  const toc = [
    "- [How to use this guide](#how-to-use-this-guide)",
    ...CHAPTERS.map(([k, t]) => `- [${t}](#${slug(t)}) (${channels.filter((c) => c.chapter === k).length})`),
    "- [Contributing](#contributing)",
  ].join("\n");
  const chapters = CHAPTERS.map(([k, t, blurb]) => {
    const list = channels.filter((c) => c.chapter === k).sort((a, b) => a.name.localeCompare(b.name));
    return `## ${t}\n\n${blurb}\n\n${list.map(entryMd).join("\n")}`;
  }).join("\n\n");
  return `<!-- Generated by build.mjs from channels.json and intro.md. Edit those, not this. -->

# First 1000 Users: a channel guide for Western indie developers

**${channels.length} channels**, links checked ${checked}. **[Search and filter them here](https://xferdino.github.io/first-1000-users-guide/).**

● rule read on the site · ◐ read via a Reddit mirror · ○ not read on the site, so check it · ⚠ site blocks automated checks, so open it yourself

${toc}

${read("intro.md").trim()}

${chapters}

## Contributing

Found a dead link, a changed rule, or a channel that belongs here? Open an issue or a pull request. A channel should reach real users in the US or Europe and take submissions from indie developers; generic "submit your URL" directories don't qualify.

This README and \`index.html\` are generated, so don't edit them by hand. Change \`channels.json\` (one object per channel) or \`intro.md\`, then run:

\`\`\`bash
node check-links.mjs   # re-checks every link and writes status and date back
node build.mjs         # refuses to build on dead links, missing fields or duplicates
\`\`\`

Node 20 or newer; no dependencies. If you read a channel's rule on its own site, set \`"source": "site"\`; otherwise leave it as \`"memory"\`.

## Licence

[Apache-2.0](LICENSE).
`;
}

const slug = (t) => t.toLowerCase().replace(/[^a-z0-9 -]/g, "").trim().replace(/ /g, "-");

function buildHtml(channels, checked) {
  const data = JSON.stringify({ chapters: CHAPTERS, channels, checked }).replace(/</g, "\\u003c");
  return read("page.template.html").replace("/*__DATA__*/null", data);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const channels = JSON.parse(read("channels.json"));
  const errors = validate(channels);
  if (errors.length) {
    console.error(errors.join("\n"));
    console.error(`\n${errors.length} problem(s); nothing written.`);
    process.exit(1);
  }
  const checked = channels.map((c) => c.checked).sort().at(-1);
  writeFileSync(new URL("README.md", dir), buildReadme(channels, checked));
  writeFileSync(new URL("index.html", dir), buildHtml(channels, checked));
  const by = (k) => channels.reduce((m, c) => ((m[c[k]] = (m[c[k]] ?? 0) + 1), m), {});
  console.log(`wrote README.md and index.html: ${channels.length} channels, checked ${checked}`);
  console.log("status:", by("status"), " rule source:", by("source"));
}
